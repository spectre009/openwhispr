const DatabaseManager = require("../../src/helpers/database.js");

// The upgrade a daily install takes when upstream's account scoping (#2924)
// lands: a History database exactly as the fork's main (fa95c00e) wrote it,
// with every fork table holding rows (dictionary words with pins, categories,
// suggestions and evidence; transcriptions with steps under two owners, a
// review, a failed row and a synced one; a test case; a snippet), opened by
// the merged DatabaseManager. Upstream adds account_id to transcriptions,
// custom_dictionary and snippets and rebuilds custom_dictionary without its
// device-wide UNIQUE(word); the fork's own migrations run after it. Nothing
// may be lost, every row must be visible to the account that owns it and to
// the signed-out state while it is unattributed, and the fork's content
// triggers must survive the rebuild.
//
// test/fixtures/forkMainDatabase.json is that database: its schema in
// creation order and its rows, generated by running main's DatabaseManager
// (setActiveAccountId, saveTranscription with steps, saveDictationFeedback,
// applyDictionaryChanges, setDictionaryPin, reorderDictionaryPins,
// setDictionaryCategories, recordDictionarySuggestions,
// addDictionaryWordEvidence, insertPromptTestCase, setSnippets).
// Run under Electron's Node with REQUIRE_DB_TESTS=1; plain Node skips.

const FIXTURE = require("../fixtures/forkMainDatabase.json");
const A = "acct-a";
const B = "acct-b";
const OWNER_A = `account:${A}`;
const OWNER_B = `account:${B}`;
const SIGNED_OUT = "signed-out";
const { t1, t2, t3, t4 } = FIXTURE.ids;
const EVERYTHING = "2000-01-01 00:00:00";

// Writes the fixture as a database file: tables, then rows (so no trigger
// fires on them), then indexes, triggers and views, as SQLite stored them.
function writeFixtureDatabase(file) {
  const BetterSqlite = require("better-sqlite3");
  const raw = new BetterSqlite(file);
  try {
    raw.pragma("foreign_keys = OFF");
    const ofType = (type) => FIXTURE.schema.filter((entry) => entry.type === type);
    raw.transaction(() => {
      for (const entry of ofType("table")) raw.exec(entry.sql);
      for (const [table, { columns, values }] of Object.entries(FIXTURE.rows)) {
        const insert = raw.prepare(
          `INSERT INTO "${table}" (${columns.map((c) => `"${c}"`).join(", ")}) VALUES (${columns
            .map(() => "?")
            .join(", ")})`
        );
        for (const row of values) {
          insert.run(
            ...row.map((value) =>
              value && typeof value === "object" && "$blob" in value
                ? Buffer.from(value.$blob, "base64")
                : value
            )
          );
        }
      }
      raw.prepare("DELETE FROM sqlite_sequence").run();
      const sequence = raw.prepare("INSERT INTO sqlite_sequence (name, seq) VALUES (?, ?)");
      for (const { name, seq } of FIXTURE.sequence) sequence.run(name, seq);
      for (const type of ["index", "trigger", "view"]) {
        for (const entry of ofType(type)) raw.exec(entry.sql);
      }
    })();
  } finally {
    raw.close();
  }
}

// main's database, migrated by the merged code. Null when the binding isn't
// loadable here (skipOrFail marked the test skipped).
function openMigrated(t) {
  const userDataDir = fs.mkdtempSync(path.join(os.tmpdir(), "openwhispr-fork-migration-"));
  setUserDataDir(userDataDir);
  try {
    writeFixtureDatabase(path.join(userDataDir, "transcriptions.db"));
  } catch (error) {
    fs.rmSync(userDataDir, { recursive: true, force: true });
    skipOrFail(t, error);
    return null;
  }
  const open = () => new DatabaseManager();
  const db = open();
  const handles = [db];
  t.after(() => {
    for (const handle of handles) {
      try {
        handle.db?.close();
      } catch {
        // an already-closed handle must not mask the test's own failure
      }
    }
    fs.rmSync(userDataDir, { recursive: true, force: true });
  });
  // A second launch over the migrated file.
  db.reopen = () => {
    db.db.close();
    const next = open();
    handles.push(next);
    return next;
  };
  return db;
}

// set-active-account-scope's database steps (ipcHandlers.js), in its order.
function signIn(db, accountId) {
  db.setActiveAccountId(accountId);
  db.claimSignedOutLocalRows();
  db.claimLegacyRowsOfOnlyAccount();
}

const fixtureRows = (table) => {
  const { columns, values } = FIXTURE.rows[table];
  return values.map((row) => Object.fromEntries(columns.map((c, i) => [c, row[i]])));
};
const count = (db, table) => db.db.prepare(`SELECT COUNT(*) AS n FROM "${table}"`).get().n;
const pageIds = (db, owner) => db.getHistoryPage({ owner, limit: 50 }).map((row) => row.id);
const liveWords = ["Kubernetes", "OpenWhispr", "Dmitri", "kubectl", "Zebrafish"];

test("main's database migrates with every row of every fork table intact", (t) => {
  const db = openMigrated(t);
  if (!db) return;
  for (const table of Object.keys(FIXTURE.rows)) {
    if (["history_content_revision", "dictionary_content_revision"].includes(table)) continue;
    assert.equal(count(db, table), FIXTURE.rows[table].values.length, table);
  }

  // Same ids, same contents; upstream's new columns mark them pre-attribution.
  for (const table of ["transcriptions", "custom_dictionary", "snippets"]) {
    const after = new Map(
      db.db
        .prepare(`SELECT * FROM "${table}"`)
        .all()
        .map((row) => [row.id, row])
    );
    for (const before of fixtureRows(table)) {
      const row = after.get(before.id);
      assert.ok(row, `${table} ${before.id}`);
      for (const [column, value] of Object.entries(before)) {
        assert.equal(row[column], value, `${table} ${before.id}.${column}`);
      }
      assert.equal(row.account_id, null, `${table} ${before.id} account_id`);
      assert.equal(row.legacy_unattributed, 1, `${table} ${before.id} legacy_unattributed`);
    }
  }
  for (const table of [
    "transcription_steps",
    "dictation_feedback",
    "prompt_test_cases",
    "dictionary_pins",
    "dictionary_categories",
    "dictionary_suggestions",
    "dictionary_word_evidence",
    "prompt_versions",
  ]) {
    const before = fixtureRows(table);
    const after = db.db.prepare(`SELECT * FROM "${table}"`).all();
    assert.deepEqual(
      after.map((row) => Object.fromEntries(Object.keys(before[0]).map((c) => [c, row[c]]))),
      before,
      table
    );
  }

  // custom_dictionary lost the device-wide UNIQUE(word), gained the per-account one,
  // and keeps its AUTOINCREMENT high-water mark.
  const indexes = db.db
    .prepare(
      "SELECT name FROM sqlite_master WHERE type = 'index' AND tbl_name = 'custom_dictionary'"
    )
    .all()
    .map((row) => row.name);
  assert.ok(!indexes.some((name) => name.startsWith("sqlite_autoindex_custom_dictionary")));
  assert.ok(indexes.includes("idx_custom_dictionary_account_word"));
  const sequence = (name) =>
    db.db.prepare("SELECT seq FROM sqlite_sequence WHERE name = ?").get(name)?.seq;
  for (const { name, seq } of FIXTURE.sequence) {
    if (seq > 0) assert.ok(sequence(name) >= seq, `sqlite_sequence ${name}`);
  }

  // The fork's content triggers were dropped with the old table and are back.
  const triggers = db.db
    .prepare("SELECT name, tbl_name FROM sqlite_master WHERE type = 'trigger'")
    .all();
  const on = (table) => triggers.filter((tr) => tr.tbl_name === table).map((tr) => tr.name);
  for (const name of [
    "custom_dictionary_generation_insert",
    "custom_dictionary_generation_update",
    "custom_dictionary_generation_delete",
    "custom_dictionary_client_id_default",
  ]) {
    assert.ok(on("custom_dictionary").includes(name), name);
  }
  for (const name of [
    "transcriptions_content_revision_insert",
    "transcriptions_content_revision_update",
    "transcriptions_content_revision_delete",
  ]) {
    assert.ok(on("transcriptions").includes(name), name);
  }
  // The migration itself changed no content: neither counter moved.
  const revision = (table) =>
    db.db.prepare(`SELECT revision FROM ${table} WHERE id = 1`).get().revision;
  assert.equal(
    revision("history_content_revision"),
    fixtureRows("history_content_revision")[0].revision
  );
  assert.equal(
    revision("dictionary_content_revision"),
    fixtureRows("dictionary_content_revision")[0].revision
  );
  // ...and they still fire on the rebuilt table.
  const dictionaryBefore = revision("dictionary_content_revision");
  db.applyDictionaryChanges({ add: ["Prometheus"] });
  assert.equal(revision("dictionary_content_revision"), dictionaryBefore + 1);
  db.applyDictionaryChanges({ remove: ["Prometheus"] });
  assert.equal(revision("dictionary_content_revision"), dictionaryBefore + 2);

  // A second launch changes nothing more.
  const again = db.reopen();
  for (const table of ["transcriptions", "custom_dictionary", "transcription_steps"]) {
    assert.equal(count(again, table), FIXTURE.rows[table].values.length, `${table} after reopen`);
  }
});

test("signed out before any sign-in, the unattributed rows and the signed-out steps are in view", (t) => {
  const db = openMigrated(t);
  if (!db) return;
  assert.deepEqual(pageIds(db, SIGNED_OUT), [t4, t3, t2, t1]);
  assert.equal(db.getTranscriptionSteps(t2, SIGNED_OUT).status, "captured");
  assert.equal(db.getTranscriptionSteps(t1, SIGNED_OUT).status, "otherOwner");
  assert.deepEqual(db.getDictionary(), liveWords);
  assert.deepEqual(db.getDictionaryPins(), ["dmitri", "kubernetes"]);
  assert.equal(db.getDictionaryCategories().length, 2);
  assert.equal(db.getHistoryItem(t1)?.text, "Deploy with kubectl to Kubernetes.");
});

test("signed in as the account that wrote them, its rows, steps, review, words, pins, categories and case are all there", (t) => {
  const db = openMigrated(t);
  if (!db) return;
  signIn(db, A);

  assert.deepEqual(pageIds(db, OWNER_A), [t4, t3, t2, t1]);
  const steps = db.getHistoryStepRows([t1, t2, t3, t4], OWNER_A);
  assert.deepEqual(
    steps.map((step) => [step.transcription_id, step.seq, step.kind, step.outcome]),
    [
      [t1, 0, "transcription", "ok"],
      [t1, 1, "cleanup", "ok"],
      [t3, 0, "transcription", "ok"],
      [t3, 1, "cleanup", "error"],
    ]
  );
  const captured = db.getTranscriptionSteps(t1, OWNER_A);
  assert.equal(captured.status, "captured");
  assert.equal(captured.rows[1].prompt_text, "Clean up the dictation.");
  // The review is of the row as it still is: not stale, with its correction.
  const review = db.getDictationFeedback(t1, OWNER_A);
  assert.equal(review.verdict, "bad");
  assert.equal(review.expected_text, "Deploy with kubectl to Kubernetes now.");
  assert.equal(review.revision, db.getHistoryRevision(t1, OWNER_A));
  assert.equal(db.getLastReviewableDictation(OWNER_A), t3);
  assert.deepEqual(db.getHistoryApps(OWNER_A), ["Code.exe"]);
  assert.equal(db.getHistoryItem(t1).has_audio, 1);

  assert.deepEqual(db.getDictionary(), liveWords);
  assert.deepEqual(
    db.getDictionaryEntries().map((entry) => [entry.word, entry.source]),
    liveWords.map((word) => [word, word === "Zebrafish" ? "learned" : "manual"])
  );
  assert.deepEqual(db.getDictionaryPins(), ["dmitri", "kubernetes"]);
  assert.deepEqual(
    db.getDictionaryCategories().map((row) => [row.key, row.category, row.source]),
    [
      ["dmitri", "people", "user"],
      ["kubernetes", "work", "model"],
    ]
  );
  const suggestions = db.getDictionarySuggestions();
  assert.deepEqual(
    suggestions.suggestions.map((row) => row.word),
    ["Prometheus"]
  );
  assert.equal(suggestions.dismissed, 1);
  assert.deepEqual(
    db.getDictionaryWordEvidence(OWNER_A).map((row) => [row.word_key, row.transcription_id]),
    [["kubectl", t1]]
  );
  assert.deepEqual(
    db.getPromptTestCases(OWNER_A).map((row) => [row.id, row.source_transcription_id]),
    [["case-1", t1]]
  );
  assert.deepEqual(
    db.getSnippets().map((row) => [row.trigger, row.replacement]),
    [["sig", "Best, Dmitri"]]
  );
  // The heard/written counts read the same rows History shows.
  assert.deepEqual(
    db.getDictionaryOccurrenceRows({ owner: OWNER_A, since: EVERYTHING }).map((row) => row.id),
    [t4, t2, t1]
  );

  // Signed out again, the device's only account stays in view.
  signIn(db, null);
  assert.deepEqual(pageIds(db, SIGNED_OUT), [t4, t3, t2, t1]);
  assert.equal(db.getTranscriptionSteps(t2, SIGNED_OUT).status, "captured");
  assert.deepEqual(db.getDictionary(), liveWords);
  assert.deepEqual(db.getDictionaryPins(), ["dmitri", "kubernetes"]);
});

test("a second account sees only unattributed rows, and switching never prunes the first account's pins or categories", (t) => {
  const db = openMigrated(t);
  if (!db) return;
  // The only account on the device takes its legacy rows no cloud holds.
  signIn(db, A);
  signIn(db, B);

  // B: the rows a cloud holds wait, unattributed, for their owner to prove them.
  assert.deepEqual(pageIds(db, OWNER_B), [t4]);
  assert.equal(db.getHistoryItem(t1), null);
  assert.equal(db.getTranscriptionSteps(t1, OWNER_B).status, "none");
  assert.equal(db.getDictationFeedback(t1, OWNER_A), null, "not A's review while B is in view");
  assert.deepEqual(db.getDictionary(), ["OpenWhispr"]);
  assert.deepEqual(db.getDictionaryPins(), []);
  assert.deepEqual(db.getDictionaryCategories(), []);
  // A word B adds and removes prunes nothing of A's.
  db.applyDictionaryChanges({ add: ["Ephemeral"] });
  db.applyDictionaryChanges({ remove: ["Ephemeral"] });
  // The same word in two accounts (UNIQUE(word) is per account now): B's
  // Kubernetes shares A's pin and category, which are keyed by the word.
  assert.equal(db.applyDictionaryChanges({ add: ["Kubernetes"] }).added, 1);
  assert.deepEqual(db.getDictionary(), ["OpenWhispr", "Kubernetes"]);
  assert.deepEqual(db.getDictionaryPins(), ["kubernetes"]);
  assert.equal(
    db.db.prepare("SELECT COUNT(*) AS n FROM custom_dictionary WHERE word = 'Kubernetes'").get().n,
    2
  );
  // Clear history as B: only B's view goes.
  db.clearTranscriptions();
  assert.deepEqual(pageIds(db, OWNER_B), []);

  // Signed out on a shared device: unattributed rows only.
  signIn(db, null);
  assert.deepEqual(pageIds(db, SIGNED_OUT), []);

  // Back to A: everything A owns, with its steps, review, pins and categories.
  signIn(db, A);
  assert.deepEqual(pageIds(db, OWNER_A), [t3, t2, t1]);
  assert.equal(db.getHistoryStepRows([t1, t3], OWNER_A).length, 4);
  assert.equal(db.getDictationFeedback(t1, OWNER_A).verdict, "bad");
  // A's words, and the unattributed one a cloud holds (still everyone's until proven).
  assert.deepEqual(db.getDictionary(), liveWords);
  assert.deepEqual(db.getDictionaryPins(), ["dmitri", "kubernetes"]);
  assert.deepEqual(
    db.getDictionaryCategories().map((row) => row.key),
    ["dmitri", "kubernetes"]
  );
  assert.equal(db.getPromptTestCases(OWNER_A).length, 1);
  assert.equal(db.getDictionaryWordEvidence(OWNER_A).length, 1);
});
